/** The IANA zone for a Xero Organisation.Timezone, or undefined when it isn't one we know. */
export function xeroTimeZone(windowsId: unknown): string | undefined {
  if (typeof windowsId !== 'string') return undefined
  return WINDOWS_TO_IANA[windowsId.replace(/[^A-Za-z]/g, '').toUpperCase()]
}
